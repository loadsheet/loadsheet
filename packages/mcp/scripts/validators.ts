import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { Ajv } from "ajv";
import { Ajv2020 } from "ajv/dist/2020.js";

const require = createRequire(import.meta.url);
// The standalone entry is CommonJS, which Node and TypeScript read different default exports from.
const standaloneCode: typeof import("ajv/dist/standalone/index.js").default = require("ajv/dist/standalone/index.js");

export const DRAFT_2020_12 = "https://json-schema.org/draft/2020-12/schema";
export const DRAFT_07 = "http://json-schema.org/draft-07/schema";

// Formats stay off: no client documents checking `format: "regex"` and the like, and a false
// exclusion costs more than a missed one.
const options = { strict: false, validateFormats: false, code: { source: true, esm: true } };

// Standalone code still `require`s Ajv's runtime helper for `enum`, `const` and `uniqueItems`, even
// as ESM. Inlining it leaves the package with no runtime dependency.
const EQUAL_REQUIRE = 'require("ajv/dist/runtime/equal").default';

/** The standalone validator modules, by file name in src/generated. */
export function validatorModules(): Record<string, string> {
  return {
    "draft2020.js": module(new Ajv2020(options), DRAFT_2020_12),
    "draft07.js": module(new Ajv(options), DRAFT_07),
  };
}

function module(ajv: Ajv, id: string): string {
  const code = standaloneCode(ajv, { validate: id });
  const inlined = code.replaceAll(EQUAL_REQUIRE, "equal");
  if (/\brequire\(/.test(inlined))
    throw new Error(
      `ajv's standalone code for ${id} requires a module this script doesn't inline.`,
    );
  const helper = code.includes(EQUAL_REQUIRE) ? `\n${equalSource()}` : "";
  return `// Generated by scripts/generate.ts from ajv's ${id} meta-schema. Do not edit.\n${inlined}${helper}\n`;
}

function equalSource(): string {
  const fromAjv = createRequire(require.resolve("ajv"));
  const path = fromAjv.resolve("fast-deep-equal");
  const source = readFileSync(path, "utf8");
  const body = source.slice(source.indexOf("module.exports = function equal"));
  return `// fast-deep-equal ${fromAjv("fast-deep-equal/package.json").version}, MIT License, Copyright (c) 2017 Evgeny Poberezkin.\n${body
    .replace("module.exports = function equal", "function equal")
    .trim()
    .replace(/;$/, "")}`;
}
